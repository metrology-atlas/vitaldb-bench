"""Write docs/reference/tools.md: every script in tools/ with the first paragraph of its docstring.

    python tools/gen_tools_page.py

Run it after adding or renaming a script. Reads only the scripts' source; no data.
"""

from __future__ import annotations

import ast
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "docs" / "reference" / "tools.md"

HEAD = """# Analysis scripts

The scripts in `tools/` produced the tables and figures of the timing audit. They are scripts, not part of
the installed package: run them as `python tools/<name>.py` after `pip install -e ".[tools]"`. Each one's
docstring gives its commands and says what it reads and writes; per-case output stays on the analysis
machine. See [Reproduce the results](../how-to/reproduce-results.md) for which made which file.

This page is generated by `tools/gen_tools_page.py`.

| Script | What it does |
|---|---|
"""


def summary(path: Path) -> str:
    """First paragraph of a script's module docstring, on one line, safe inside a Markdown table."""
    doc = ast.get_docstring(ast.parse(path.read_text(encoding="utf-8"))) or "(no docstring)"
    para = doc.strip().split("\n\n")[0]
    return " ".join(para.split()).replace("|", "\\|")


def main() -> None:
    """Write the page."""
    rows = [f"| `{p.name}` | {summary(p)} |" for p in sorted((ROOT / "tools").glob("*.py"))]
    adhoc = ("\nShort helpers kept for provenance are in `tools/adhoc/` (see its README); they are not listed "
             "here.\n")
    OUT.write_text(HEAD + "\n".join(rows) + "\n" + adhoc, encoding="utf-8")
    print(f"{OUT.relative_to(ROOT)}: {len(rows)} scripts")


if __name__ == "__main__":
    main()
